#!/usr/bin/env python3
"""
楽天商品が「焼酎・泡盛」かどうかを判定する共通フィルタ。
whisky_filter と同設計で語彙だけ焼酎・泡盛に差し替えたもの。
蔵名キーワード検索で混入する非焼酎（服飾・グラス・書籍・他カテゴリ酒類）を除外する。
方針: 精度優先（焼酎・泡盛以外を出さない）。
"""
import re

# 非飲料（服飾・雑貨・グラス・書籍・食品）。焼酎語があっても除外
_EXCLUDE_HARD = re.compile(
    r'カーディガン|スカート|ニット|セーター|シャツ|Tシャツ|ブラウス|ワンピース|パンツ|デニム|ジーンズ'
    r'|コート|ジャケット|アウター|パーカー|スウェット|スカジャン|半纏|法被|前掛け|エプロン|木綿|手ぬぐい'
    r'|ランジェリー|インナー|下着|靴下|帽子|マフラー|手袋|スニーカー|シューズ'
    r'|バッグ|\bbag\b|カバン|鞄|財布|ポーチ|リュック|ピアス|ネックレス|ブレスレット|指輪|アクセサリ'
    r'|腕時計|掛け時計|サングラス|眼鏡|スマホケース|手芸|フィギュア|ぬいぐるみ|ボールペン|タオル|マット|クッション'
    r'|ワイングラス|ロックグラス|焼酎グラス|焼酎サーバー|グラスセット|タンブラー|食器|お皿|プレート|ボウル'
    r'|カトラリー|急須|湯呑|栓抜き|アイスペール|アイストング|黒じょか|千代香'
    r'|電子書籍|\bebook\b|kindle|楽天kobo|文庫|新書|コミック|単行本|写真集|カレンダー'
    r'|チョコレート|ケーキ|クッキー|焼き菓子|ジャム|ドレッシング|レトルト|ソーセージ|燻製|石鹸|化粧水|コスメ'
    # 原料そのもの（芋・麦・米の生鮮）が焼酎蔵名で引っかかる事故を防ぐ
    r'|生芋|さつまいも\s*\d+kg|お米\s*\d+kg|精米\s*\d+kg',
    re.IGNORECASE,
)

# 焼酎・泡盛であるシグナル（いずれか1つ以上）
_SHOCHU = re.compile(
    r'焼酎|泡盛|しょうちゅう|shochu|awamori'
    r'|芋焼酎|麦焼酎|米焼酎|黒糖焼酎|そば焼酎|蕎麦焼酎|栗焼酎|粕取|酒粕焼酎|胡麻焼酎|ごま焼酎'
    r'|本格焼酎|乙類|甲類|単式蒸留|減圧蒸留|常圧蒸留'
    r'|クース|古酒|黒麹|白麹|黄麹|黒こうじ'
    r'|前割り|お湯割り|ロック用',
    re.IGNORECASE,
)

# 焼酎の定番度数・容量は補助シグナル
_ABV = re.compile(r'(20|25|30|35|37|40|43)\s*(度|%|％)')
_VOL = re.compile(r'(1800|1\.8|900|720|750|600|500|360|300|200|180)\s?(ml|mL|ML|L|リットル)|一升|五合|四合', re.IGNORECASE)

# 他カテゴリの酒類（焼酎語が無い場合のみ除外）
_EXCLUDE_BOOZE = re.compile(
    r'日本酒|清酒|純米|吟醸|本醸造|大吟醸|どぶろく|にごり酒'
    r'|ワイン|\bwine\b|ヴァン|スパークリング|シャンパン'
    r'|ウイスキー|ウィスキー|whisky|whiskey|シングルモルト|バーボン|スコッチ'
    r'|ビール|発泡酒|\bbeer\b|クラフトビール|エール|ラガー'
    r'|梅酒|果実酒|リキュール|サワー|チューハイ|甘酒|ジン|\bgin\b|ウォッカ|ラム酒',
    re.IGNORECASE,
)


def is_shochu_item(name: str) -> bool:
    """商品名が焼酎・泡盛として妥当ならTrue。"""
    if not name:
        return False
    if _EXCLUDE_HARD.search(name):       # 非飲料
        return False
    if _SHOCHU.search(name):             # 焼酎・泡盛シグナル → 採用
        return True
    if _EXCLUDE_BOOZE.search(name):      # 他カテゴリ酒類 → 除外
        return False
    if _ABV.search(name) and _VOL.search(name):  # 度数＋容量があり除外語も無い → 焼酎とみなす
        return True
    return False


if __name__ == '__main__':
    tests = [
        ('霧島酒造 黒霧島 25度 1800ml', True),
        ('【ふるさと納税】都城市 本格芋焼酎 飲み比べセット', True),
        ('八海山 純米大吟醸 1800ml', False),
        ('久米仙 泡盛 古酒 43度 720ml', True),
        ('森伊蔵 芋焼酎 720ml', True),
        ('黒糖焼酎 れんと 25度 900ml', True),
        ('焼酎グラス 名入れ ロックグラス', False),
        ('グレイスワイン 甲州 750ml', False),
        ('サントリー 知多 700ml ウイスキー', False),
        ('中野BC 紀州梅酒 720ml', False),
        ('薩摩 白波 25度 1800ml パック', True),
        ('鹿児島 さつまいも 5kg 生芋', False),
    ]
    ok = 0
    for nm, exp in tests:
        got = is_shochu_item(nm)
        m = 'OK' if got == exp else 'NG'
        if got == exp:
            ok += 1
        print(f'  [{m}] {got!s:5} (期待{exp!s:5}) {nm}')
    print(f'\n{ok}/{len(tests)} passed')
